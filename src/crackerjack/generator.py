def load_wordlist(path: Optional[Path] = None) -> list[str]:
    """Load distinct words from a custom file or fallback to DEFAULT_PASSPHRASE_WORDS."""
    if path and path.is_file():
        try:
            words = [
                line.strip().lower()
                for line in path.read_text(encoding="utf-8", errors="ignore").splitlines()
                if line.strip() and not line.startswith("#") and len(line.strip()) >= 3
            ]
            if len(words) >= 100:
                return sorted(list(set(words)))
        except Exception:
            pass
    return DEFAULT_PASSPHRASE_WORDS


def generate_passphrase(
    word_count: int = 4,
    separator: str = "-",
    capitalize: bool = False,
    add_number: bool = False,
    add_symbol: bool = False,
    wordlist_path: Optional[Path] = None,
    check_breach: bool = False,
) -> GeneratedPassphrase:
    """Generate a cryptographically secure, NIST-compliant multi-word passphrase."""
    word_count = max(3, min(word_count, 12))
    pool = load_wordlist(wordlist_path)
    pool_size = len(pool)

    # Use secrets.choice for CSPRNG selection
    selected_words = [secrets.choice(pool) for _ in range(word_count)]

    if capitalize:
        selected_words = [w.capitalize() for w in selected_words]

    passphrase = separator.join(selected_words)

    # Add optional random number
    if add_number:
        num = secrets.randbelow(900) + 100  # 3-digit number (100-999)
        passphrase = f"{passphrase}{separator}{num}"

    # Add optional symbol
    if add_symbol:
        symbols = "!@#$%^&*+=?"
        sym = secrets.choice(symbols)
        passphrase = f"{passphrase}{sym}"

    # Theoretical entropy calculation: E = log2(N^W) = W * log2(N)
    theoretical_entropy = word_count * math.log2(pool_size)
    if add_number:
        theoretical_entropy += math.log2(900)
    if add_symbol:
        theoretical_entropy += math.log2(11)
    if capitalize:
        theoretical_entropy += word_count * math.log2(2)

    # Evaluate using the NIST SP 800-63B policy auditor
    nist_eval = evaluate_password(passphrase)

    # Optional breach checking
    breached = False
    breach_count = 0
    if check_breach:
        try:
            from crackerjack.breach import check_password_breached
            breach_res = check_password_breached(passphrase)
            breached = breach_res.pwned
            breach_count = breach_res.breach_count
        except Exception:
            pass

    return GeneratedPassphrase(
        passphrase=passphrase,
        word_count=word_count,
        separator=separator,
        entropy_bits=theoretical_entropy,
        effective_entropy_bits=nist_eval.effective_entropy_bits,
        nist_score=nist_eval.score,
        nist_grade=nist_eval.grade,
        breached=breached,
        breach_count=breach_count,
    )
